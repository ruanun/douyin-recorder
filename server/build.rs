fn main() {
    embed_web_assets();
}

/// Generates `web_assets.rs` in OUT_DIR exposing every file under ../dist,
/// so the server binary ships as a single self-contained executable.
fn embed_web_assets() {
    let dist = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../dist");
    let out_dir = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let mut files = Vec::new();
    collect_assets(&dist, &dist, &mut files);
    if files.is_empty() {
        println!(
            "cargo:warning=web frontend dist/ is empty; build the frontend first (pnpm build)"
        );
    }
    let mut generated = String::from(
        "// Auto-generated by build.rs from ../dist.\n\
         pub struct WebAsset { pub path: &'static str, pub content_type: &'static str, pub bytes: &'static [u8] }\n\
         pub fn asset(request_path: &str) -> Option<WebAsset> {\n\
         let path = request_path.trim_start_matches('/');\n\
         match path {\n",
    );
    for (path, content_type, bytes_path) in &files {
        generated.push_str(&format!(
            "\"{path}\" => Some(WebAsset {{ path: \"{path}\", content_type: \"{content_type}\", bytes: include_bytes!(\"{bytes_path}\") }}),\n"
        ));
    }
    generated.push_str("_ => None,\n}\n}\n\n");
    generated.push_str("/// Path used for SPA fallback (theme shell).\npub fn index_asset() -> Option<WebAsset> { asset(\"index.html\") }\n");
    std::fs::write(out_dir.join("web_assets.rs"), generated)
        .expect("failed to write generated web assets");
    println!("cargo:rerun-if-changed=../dist");
}

fn collect_assets(
    root: &std::path::Path,
    dir: &std::path::Path,
    out: &mut Vec<(String, String, String)>,
) {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(_) => return,
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_assets(root, &path, out);
            continue;
        }
        let rel = path
            .strip_prefix(root)
            .unwrap()
            .to_string_lossy()
            .replace('\\', "/");
        let content_type = match path.extension().and_then(|e| e.to_str()) {
            Some("html") => "text/html; charset=utf-8",
            Some("js") => "text/javascript; charset=utf-8",
            Some("css") => "text/css; charset=utf-8",
            Some("svg") => "image/svg+xml",
            Some("png") => "image/png",
            Some("ico") => "image/x-icon",
            Some("json") => "application/json",
            Some("woff2") => "font/woff2",
            Some("map") => "application/json",
            _ => "application/octet-stream",
        };
        out.push((
            rel,
            content_type.to_string(),
            path.to_string_lossy().replace('\\', "/"),
        ));
    }
}
